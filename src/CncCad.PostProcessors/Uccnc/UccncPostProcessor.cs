using System.Globalization;
using System.Text;
using CncCad.Cam.Toolpaths;
using CncCad.PostProcessors.GCode;
using CncCad.PostProcessors.Models;

namespace CncCad.PostProcessors.Uccnc;

public sealed class UccncPostProcessor : IPostProcessor
{
    public string Name => "UCCNC";
    public string FileExtension => ".nc";
    private static string N(double value) => value.ToString("0.000", CultureInfo.InvariantCulture);
    private static double X(double value,MachineProfile machine)=>value-machine.WorkZeroDocumentXmm;
    private static double Y(double value,MachineProfile machine)=>value-machine.WorkZeroDocumentYmm;
    private static double Z(double value,MachineProfile machine)=>value+machine.WorkZeroZOffsetMm;

    public string Generate(ToolpathProgram program, MachineProfile machine)
    {
        var output = new StringBuilder();
        output.AppendLine($"(Generated by CncCad - {program.Name})");
        output.AppendLine("G21");
        output.AppendLine("G90");
        output.AppendLine($"G0 Z{N(Z(machine.SafeZMm,machine))}");
        foreach (var operation in program.Operations)
        {
            output.AppendLine($"({operation.Name})");
            foreach (var move in operation.Moves)
            {
                switch (move)
                {
                    case ToolChange tool when tool.ToolNumber is not null: output.AppendLine($"T{tool.ToolNumber} M6 ({tool.ToolName})"); break;
                    case ToolChange tool: output.AppendLine($"(Tool: {tool.ToolName})"); break;
                    case SpindleStart spindle: output.AppendLine($"M3 S{spindle.Rpm}"); break;
                    case SpindleStop: output.AppendLine("M5"); break;
                    case RapidMove rapid: output.AppendLine($"G0 X{N(X(rapid.End.X,machine))} Y{N(Y(rapid.End.Y,machine))} Z{N(Z(rapid.Z,machine))}"); break;
                    case LinearMove linear: output.AppendLine($"G1 X{N(X(linear.End.X,machine))} Y{N(Y(linear.End.Y,machine))} Z{N(Z(linear.Z,machine))} F{N(linear.FeedRate)}"); break;
                    case ArcMove arc:
                        var i = arc.Center.X - arc.End.X;
                        var j = arc.Center.Y - arc.End.Y;
                        output.AppendLine($"G{(arc.Clockwise ? 2 : 3)} X{N(X(arc.End.X,machine))} Y{N(Y(arc.End.Y,machine))} Z{N(Z(arc.Z,machine))} I{N(i)} J{N(j)} F{N(arc.FeedRate)}");
                        break;
                }
            }
        }
        output.AppendLine($"G0 Z{N(Z(machine.SafeZMm,machine))}");
        output.AppendLine($"G0 X{N(machine.ParkXmm)} Y{N(machine.ParkYmm)}");
        output.AppendLine("M5");
        output.AppendLine("M30");
        return output.ToString();
    }
}
