using System.Globalization;
using System.Text;
using CncCad.Cam.Toolpaths;
using CncCad.Core.Geometry;
using CncCad.PostProcessors.GCode;
using CncCad.PostProcessors.Models;

namespace CncCad.PostProcessors.Uccnc;

public sealed class UccncPostProcessor : IPostProcessor
{
    public string Id => "uccnc-mm";
    public string Name => "UCCNC";
    public string FileExtension => ".nc";
    private static string N(double value)
    {
        if (!double.IsFinite(value)) throw new InvalidDataException("G-code contains a non-finite numeric value.");
        return value.ToString("0.000", CultureInfo.InvariantCulture);
    }
    private static double X(double value,MachineProfile machine)=>value-machine.WorkZeroDocumentXmm;
    private static double Y(double value,MachineProfile machine)=>value-machine.WorkZeroDocumentYmm;
    private static double Z(double value,MachineProfile machine)=>value+machine.WorkZeroZOffsetMm;
    private static string Comment(string? value)
    {
        var safe = string.IsNullOrWhiteSpace(value) ? "Unnamed" : value.Replace('(', '[').Replace(')', ']').Replace('\r', ' ').Replace('\n', ' ').Trim();
        return $"({safe})";
    }

    public string Generate(ToolpathProgram program, MachineProfile machine)
    {
        ArgumentNullException.ThrowIfNull(program);
        ArgumentNullException.ThrowIfNull(machine);
        if (program.Operations.Count == 0) throw new InvalidOperationException("The G-code program contains no toolpath operations.");
        _ = N(machine.SafeZMm); _ = N(machine.WorkZeroDocumentXmm); _ = N(machine.WorkZeroDocumentYmm); _ = N(machine.WorkZeroZOffsetMm); _ = N(machine.ParkXmm); _ = N(machine.ParkYmm);

        var output = new StringBuilder();
        output.AppendLine(Comment($"Generated by CncCad - {program.Name}"));
        output.AppendLine("G21");
        output.AppendLine("G90");
        output.AppendLine("G17");
        output.AppendLine("G91.1");
        output.AppendLine("G94");
        output.AppendLine("G40");
        output.AppendLine("G49");
        output.AppendLine("G80");
        Point2D? current = null;
        var spindleRunning = false;
        output.AppendLine($"G0 Z{N(Z(machine.SafeZMm,machine))}");
        foreach (var operation in program.Operations)
        {
            output.AppendLine(Comment(operation.Name));
            foreach (var move in operation.Moves)
            {
                switch (move)
                {
                    case ToolChange tool when tool.ToolNumber is <= 0: throw new InvalidDataException($"Tool '{tool.ToolName}' has an invalid tool number.");
                    case ToolChange tool when tool.ToolNumber is not null:
                        output.AppendLine($"G0 Z{N(Z(machine.SafeZMm,machine))}");
                        if (spindleRunning) { output.AppendLine("M5"); spindleRunning = false; }
                        output.AppendLine($"T{tool.ToolNumber} M6 {Comment(tool.ToolName)}");
                        break;
                    case ToolChange tool: throw new InvalidDataException($"Tool '{tool.ToolName}' does not have a tool number.");
                    case SpindleStart spindle when spindle.Rpm <= 0: throw new InvalidDataException("Spindle RPM must be greater than zero.");
                    case SpindleStart spindle when machine.MaximumSpindleRpm > 0 && spindle.Rpm > machine.MaximumSpindleRpm: throw new InvalidDataException($"Requested spindle speed {spindle.Rpm} RPM exceeds the machine maximum of {machine.MaximumSpindleRpm} RPM.");
                    case SpindleStart spindle: output.AppendLine($"M3 S{spindle.Rpm}"); spindleRunning = true; break;
                    case SpindleStop: output.AppendLine("M5"); spindleRunning = false; break;
                    case DwellMove dwell when !double.IsFinite(dwell.Seconds) || dwell.Seconds <= 0: throw new InvalidDataException("Dwell time must be a positive finite value.");
                    case DwellMove dwell: output.AppendLine($"G4 P{N(dwell.Seconds)}"); break;
                    case RapidMove rapid: current = rapid.End; output.AppendLine($"G0 X{N(X(rapid.End.X,machine))} Y{N(Y(rapid.End.Y,machine))} Z{N(Z(rapid.Z,machine))}"); break;
                    case LinearMove linear when linear.FeedRate <= 0: throw new InvalidDataException("Linear move feed rate must be greater than zero.");
                    case LinearMove linear: current = linear.End; output.AppendLine($"G1 X{N(X(linear.End.X,machine))} Y{N(Y(linear.End.Y,machine))} Z{N(Z(linear.Z,machine))} F{N(linear.FeedRate)}"); break;
                    case ArcMove when current is null: throw new InvalidDataException("An arc move must follow a positioned rapid or linear move.");
                    case ArcMove arc when arc.FeedRate <= 0: throw new InvalidDataException("Arc move feed rate must be greater than zero.");
                    case ArcMove arc:
                        var i = arc.Center.X - current.Value.X;
                        var j = arc.Center.Y - current.Value.Y;
                        output.AppendLine($"G{(arc.Clockwise ? 2 : 3)} X{N(X(arc.End.X,machine))} Y{N(Y(arc.End.Y,machine))} Z{N(Z(arc.Z,machine))} I{N(i)} J{N(j)} F{N(arc.FeedRate)}");
                        current = arc.End;
                        break;
                    case ToolpathMove unsupported: throw new InvalidDataException($"Unsupported toolpath move '{unsupported.GetType().Name}'.");
                }
            }
        }
        output.AppendLine($"G0 Z{N(Z(machine.SafeZMm,machine))}");
        output.AppendLine("M5");
        output.AppendLine($"G0 X{N(machine.ParkXmm)} Y{N(machine.ParkYmm)}");
        output.AppendLine("M30");
        return output.ToString();
    }
}
